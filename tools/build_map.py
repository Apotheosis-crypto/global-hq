"""Build hq/static/worldmap.js and hq/geo.json from world-atlas countries-110m (ISC licence, Mike Bostock).

The map is pre-projected (Natural Earth I) so the app needs no map library and works offline.
Run: python3 tools/build_map.py
"""
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
W = 1000
SCALE = (W / 2) / (0.8707 * math.pi)
H = round(2 * 1.42239 * SCALE)


def project(lon, lat):
    l, p = math.radians(lon), math.radians(lat)
    p2 = p * p
    p4 = p2 * p2
    x = l * (0.8707 - 0.131979 * p2 + p4 * (-0.013791 + p4 * (0.003971 * p2 - 0.001529 * p4)))
    y = p * (1.007226 + p2 * (0.015085 + p4 * (-0.044475 + 0.028874 * p2 - 0.005916 * p4)))
    return W / 2 + x * SCALE, H / 2 - y * SCALE


def decode(topo):
    sx, sy = topo["transform"]["scale"]
    tx, ty = topo["transform"]["translate"]
    arcs = []
    for arc in topo["arcs"]:
        x = y = 0
        pts = []
        for dx, dy in arc:
            x += dx
            y += dy
            pts.append((x * sx + tx, y * sy + ty))
        arcs.append(pts)
    return arcs


def ring(arcs, idx):
    pts = []
    for i in idx:
        a = arcs[i] if i >= 0 else arcs[~i][::-1]
        pts.extend(a if not pts else a[1:])
    return pts


def path(rings):
    out = []
    for r in rings:
        prev = None
        for lon, lat in r:
            x, y = project(lon, lat)
            cmd = "M" if prev is None or abs(x - prev) > W / 2 else "L"  # break at the antimeridian
            out.append(f"{cmd}{x:.1f},{y:.1f}")
            prev = x
        out.append("Z")
    return "".join(out)


def main():
    topo = json.loads((ROOT / "tools" / "countries-110m.json").read_text())
    arcs = decode(topo)
    countries, centroids = [], {}
    for g in topo["objects"]["countries"]["geometries"]:
        polys = [g["arcs"]] if g["type"] == "Polygon" else g.get("arcs", [])
        rings = [ring(arcs, r) for poly in polys for r in poly]
        if not rings:
            continue
        name = g["properties"]["name"]
        countries.append({"n": name, "d": path(rings)})
        outer = max((ring(arcs, poly[0]) for poly in polys), key=len)
        lon = sum(p[0] for p in outer) / len(outer)
        lat = sum(p[1] for p in outer) / len(outer)
        centroids[name] = [round(lat, 2), round(lon, 2)]
    js = "// Generated by tools/build_map.py from world-atlas (ISC). Natural Earth I projection.\n"
    js += "window.WORLD=" + json.dumps({"w": W, "h": H, "scale": SCALE, "countries": countries}, separators=(",", ":")) + ";\n"
    (ROOT / "hq" / "static" / "worldmap.js").write_text(js)
    (ROOT / "hq" / "geo.json").write_text(json.dumps(centroids, indent=0, sort_keys=True))
    print(f"{len(countries)} countries, map {W}x{H}, {len(js) // 1024} KB")


if __name__ == "__main__":
    main()
